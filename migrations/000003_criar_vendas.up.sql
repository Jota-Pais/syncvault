-- Cria a tabela de vendas: cada linha liga um produto ao canal que o vendeu.
-- Vem depois das migrations 1 e 2 porque referencia as duas tabelas.
CREATE TABLE vendas (
    -- Cria uma chave numérica gerada automaticamente pelo PostgreSQL.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Qual produto foi vendido. REFERENCES cria a chave estrangeira: o PostgreSQL
    -- recusa um produto_id que não exista em produtos(id).
    produto_id BIGINT NOT NULL REFERENCES produtos (id),
    -- Qual canal fez a venda, com a mesma garantia em canais(id).
    canal_id BIGINT NOT NULL REFERENCES canais (id),
    -- Quantas unidades saíram. Não pode passar do estoque (R1) nem invadir o estoque de segurança do canal (R3).
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    -- O preço praticado neste canal, por unidade, em centavos. Descontada a taxa, não pode ficar abaixo do custo (R2).
    preco_unitario_centavos BIGINT NOT NULL CHECK (preco_unitario_centavos > 0),
    -- O momento da venda, com fuso horário. Quem preenche é a API.
    vendida_em TIMESTAMPTZ NOT NULL
);
