-- Cria a tabela de produtos. O estoque é um só para todos os canais: é ele que
-- a venda de qualquer canal desconta (R1 e R3).
CREATE TABLE produtos (
    -- Cria uma chave numérica gerada automaticamente pelo PostgreSQL.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Guarda o nome obrigatório do produto.
    nome VARCHAR(255) NOT NULL,
    -- Quanto a loja pagou por uma unidade, em centavos (R$ 49,90 = 4990). Entra na conta da R2.
    custo_centavos BIGINT NOT NULL CHECK (custo_centavos > 0),
    -- Unidades disponíveis. O CHECK garante que nenhuma venda deixa o estoque negativo.
    estoque INTEGER NOT NULL CHECK (estoque >= 0)
);
