-- Cria a tabela de canais: os lugares onde a loja vende, como o balcão da loja
-- física e os marketplaces.
CREATE TABLE canais (
    -- Cria uma chave numérica gerada automaticamente pelo PostgreSQL.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Guarda o nome obrigatório do canal.
    nome VARCHAR(100) NOT NULL,
    -- A comissão que o canal fica de cada venda, em percentual inteiro (16 = 16%). No balcão é 0. Entra na conta da R2.
    taxa_percentual INTEGER NOT NULL CHECK (taxa_percentual BETWEEN 0 AND 100),
    -- Quantas unidades este canal não pode vender, porque o marketplace atualiza o estoque com atraso (R3). No balcão é 0.
    estoque_seguranca INTEGER NOT NULL CHECK (estoque_seguranca >= 0)
);
